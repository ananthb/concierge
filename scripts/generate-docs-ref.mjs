#!/usr/bin/env node
/**
 * Generate code-driven reference documentation for mdBook under
 * `docs/src/reference/` directly from `wrangler.toml`, `src/`, and `migrations/`.
 *
 * Zero external dependencies. Run via:
 *   node scripts/generate-docs-ref.mjs
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, 'docs', 'src', 'reference');
mkdirSync(OUT_DIR, { recursive: true });

function walkRs(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkRs(full));
    } else if (entry.name.endsWith('.rs')) {
      files.push(full);
    }
  }
  return files.sort();
}

const rsFiles = walkRs(join(ROOT, 'src'));
const rsContents = new Map(rsFiles.map((f) => [relative(ROOT, f), readFileSync(f, 'utf8')]));

// ---------------------------------------------------------------------------
// 1. bindings-and-env.md
// ---------------------------------------------------------------------------
function generateBindingsAndEnv() {
  const wrangler = readFileSync(join(ROOT, 'wrangler.toml'), 'utf8');

  const workerName = wrangler.match(/^name\s*=\s*"([^"]+)"/m)?.[1] ?? 'unknown';
  const compatDate = wrangler.match(/^compatibility_date\s*=\s*"([^"]+)"/m)?.[1] ?? 'unknown';
  const assetsDir = wrangler.match(/\[assets\]\s*\ndirectory\s*=\s*"([^"]+)"/m)?.[1] ?? './public';
  const d1Binding = wrangler.match(/\[\[d1_databases\]\][\s\S]*?binding\s*=\s*"([^"]+)"/)?.[1] ?? 'DB';
  const d1Name = wrangler.match(/\[\[d1_databases\]\][\s\S]*?database_name\s*=\s*"([^"]+)"/)?.[1] ?? 'replybots';
  const aiBinding = wrangler.match(/\[ai\]\s*\nbinding\s*=\s*"([^"]+)"/m)?.[1] ?? 'AI';
  const emailBinding = wrangler.match(/\[\[send_email\]\]\s*\nname\s*=\s*"([^"]+)"/m)?.[1] ?? 'EMAIL';

  // Extract [vars] section
  const varsSection = wrangler.match(/\[vars\]\s*\n([\s\S]*?)(?:\n\[|$)/)?.[1] ?? '';
  const staticVars = [];
  for (const line of varsSection.split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)\s*=\s*"([^"]*)"/);
    if (m) staticVars.push({ name: m[1], value: m[2] });
  }

  // Extract commented docs in wrangler.toml for vars and secrets
  const wranglerDocs = new Map();
  for (const line of wrangler.split('\n')) {
    const m = line.match(/^#\s{2,}([A-Z0-9_]+)\s+(.+)$/);
    if (m) wranglerDocs.set(m[1], m[2].trim());
  }

  // Scan src/**/*.rs for .var("...") and .secret("...")
  const varsMap = new Map();
  const secretsMap = new Map();
  const varRe = /\.\s*var\(\s*"([A-Z0-9_]+)"\s*\)/g;
  const secretRe = /\.\s*secret\(\s*"([A-Z0-9_]+)"\s*\)/g;

  for (const [file, content] of rsContents) {
    for (const m of content.matchAll(varRe)) {
      if (!varsMap.has(m[1])) varsMap.set(m[1], new Set());
      varsMap.get(m[1]).add(file);
    }
    for (const m of content.matchAll(secretRe)) {
      if (!secretsMap.has(m[1])) secretsMap.set(m[1], new Set());
      secretsMap.get(m[1]).add(file);
    }
  }

  // Also include wrangler-documented vars that may be read via helpers
  for (const [k] of wranglerDocs) {
    if (!varsMap.has(k) && !secretsMap.has(k)) {
      // Check if it's in the Secrets block vs Vars block in wrangler.toml
      const idx = wrangler.indexOf(`#   ${k}`);
      const secretsIdx = wrangler.indexOf('# Secrets the worker reads');
      if (secretsIdx !== -1 && idx > secretsIdx && idx < wrangler.indexOf('# Optional overrides')) {
        secretsMap.set(k, new Set(['wrangler.toml']));
      } else {
        varsMap.set(k, new Set(['wrangler.toml']));
      }
    }
  }

  const lines = [
    '# Bindings & Environment',
    '',
    '<!-- Generated by scripts/generate-docs-ref.mjs from wrangler.toml and src/ -->',
    '',
    `Worker name: \`${workerName}\` (compatibility date \`${compatDate}\`).`,
    '',
    '## Cloudflare Bindings',
    '',
    '| Binding | Type | Target / Config |',
    '|---|---|---|',
    `| \`${d1Binding}\` | D1 Database | \`database_name = "${d1Name}"\` |`,
    `| \`${aiBinding}\` | Workers AI | Reply generation, injection & safety guardrails |`,
    `| \`${emailBinding}\` | Send Email | Outbound platform-to-tenant handoff alerts |`,
    `| — | Static Assets | \`directory = "${assetsDir}"\` |`,
    '',
    '## Environment Variables (`[vars]`)',
    '',
  ];

  if (staticVars.length > 0) {
    lines.push('Default values in `wrangler.toml`:', '');
    for (const v of staticVars) {
      lines.push(`- \`${v.name}\` = \`"${v.value}"\``);
    }
    lines.push('');
  }

  lines.push(
    '| Variable | Description | Read in |',
    '|---|---|---|',
  );
  for (const name of [...varsMap.keys()].sort()) {
    const desc = wranglerDocs.get(name) ?? 'Runtime variable';
    const files = [...varsMap.get(name)].map((f) => `\`${f}\``).join(', ');
    lines.push(`| \`${name}\` | ${desc} | ${files} |`);
  }

  lines.push(
    '',
    '## Secrets (`wrangler secret put`)',
    '',
    '| Secret | Description | Read in |',
    '|---|---|---|',
  );
  for (const name of [...secretsMap.keys()].sort()) {
    const desc = wranglerDocs.get(name) ?? 'Worker secret';
    const files = [...secretsMap.get(name)].map((f) => `\`${f}\``).join(', ');
    lines.push(`| \`${name}\` | ${desc} | ${files} |`);
  }
  lines.push('');

  writeFileSync(join(OUT_DIR, 'bindings-and-env.md'), lines.join('\n'));
}

// ---------------------------------------------------------------------------
// 2. routes.md
// ---------------------------------------------------------------------------
function generateRoutes() {
  const libRs = rsContents.get('src/lib.rs') ?? '';
  const apiModRs = rsContents.get('src/api/mod.rs') ?? '';

  // Parse is_app_route
  const spaBlock = libRs.match(/fn is_app_route[\s\S]*?\n\}/)?.[0] ?? '';
  const spaPaths = [...spaBlock.matchAll(/"(\/[^"]*)"/g)].map((m) => m[1]);

  // Parse match path in handle_request
  const matchBlock = libRs.match(/match path \{[\s\S]*?\n    \}/)?.[0] ?? '';
  const staticPaths = [...matchBlock.matchAll(/"(\/[^"]*)"\s*=>/g)].map((m) => m[1]);

  // Parse /api/* sub-routes in src/api/mod.rs and sub-modules
  const apiRoutes = [];
  for (const m of apiModRs.matchAll(/\["([^"]+)"(?:,\s*"([^"]+)")?(?:,\s*rest @ \.\.)?\]\s*(?:if method == Method::(\w+)\s*)?=>/g)) {
    const segs = [m[1], m[2]].filter(Boolean).join('/');
    const method = m[3] ? m[3].toUpperCase() : '*';
    if (m[0].includes('rest @ ..')) {
      // Inspect submodule if available
      const subFile = `src/api/${m[1]}.rs`;
      const subSrc = rsContents.get(subFile);
      if (subSrc) {
        for (const sm of subSrc.matchAll(/\((?:Method::(\w+),\s*)?\[([^\]]*)\]\)\s*=>/g)) {
          const smMethod = sm[1] ? sm[1].toUpperCase() : '*';
          const parts = [...sm[2].matchAll(/"([^"]+)"/g)].map((p) => p[1]);
          const wildcard = sm[2].includes('_') && parts.length === 0 ? ['*'] : sm[2].includes(', _') ? [...parts, ':id'] : parts;
          apiRoutes.push({ method: smMethod, path: `/api/${segs}${wildcard.length ? '/' + wildcard.join('/') : ''}` });
        }
        // Also handle simple `match (method, rest)` or `match rest`
        if (!subSrc.match(/\((?:Method::\w+,\s*)?\[/)) {
          apiRoutes.push({ method: '*', path: `/api/${segs}/*` });
        }
      } else {
        apiRoutes.push({ method, path: `/api/${segs}/*` });
      }
    } else {
      apiRoutes.push({ method, path: `/api/${segs}` });
    }
  }

  const lines = [
    '# Routes & Endpoints',
    '',
    '<!-- Generated by scripts/generate-docs-ref.mjs from src/lib.rs and src/api/ -->',
    '',
    '## Webhooks & Callbacks',
    '',
    '| Method | Path | Handler |',
    '|---|---|---|',
    '| `GET`, `POST` | `/webhook/whatsapp` | WhatsApp Cloud API verification & inbound messages (`src/handlers/webhook.rs`) |',
    '| `POST` | `/webhook/razorpay` | Razorpay payment webhook, HMAC-SHA256 verified (`src/billing/webhook.rs`) |',
    '| `POST` | `/data-deletion` | Meta data-deletion callback (`src/handlers/data_deletion.rs`) |',
    '| `GET` | `/auth/login`, `/auth/callback` | Google OAuth sign-in (`src/handlers/auth.rs`) |',
    '| `POST` | `/auth/dev-login` | Local dev sign-in when `DEV_MODE=1` (`src/handlers/auth.rs`) |',
    '| `POST` | `/whatsapp/signup/callback` | Meta Embedded Signup completion (`src/handlers/whatsapp_signup.rs`) |',
    '',
    '## Health & Static Assets',
    '',
    'Static files in `public/` are served directly by Cloudflare\'s `[assets]` edge layer before the Worker runs. Built-in Worker routes:',
    '',
    ...staticPaths.map((p) => `- \`${p}\``),
    '',
    '## JSON API (`/api/*`)',
    '',
    'Mutations (`POST`, `PUT`, `DELETE`) require the `X-Replybots-Request: 1` header (`src/api/mod.rs`).',
    '',
    '| Method | Path |',
    '|---|---|',
  ];

  const seen = new Set();
  for (const r of apiRoutes) {
    const key = `${r.method} ${r.path}`;
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(`| \`${r.method}\` | \`${r.path}\` |`);
  }

  lines.push(
    '',
    '## SPA Shell Routes',
    '',
    'Handled by `is_app_route` in `src/lib.rs` (plus `/wizard/*`):',
    '',
    ...spaPaths.map((p) => `- \`${p}\``),
    '',
  );

  writeFileSync(join(OUT_DIR, 'routes.md'), lines.join('\n'));
}

// ---------------------------------------------------------------------------
// 3. schema.md
// ---------------------------------------------------------------------------
function generateSchema() {
  const migDir = join(ROOT, 'migrations');
  const files = readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort();
  const sql = files.map((f) => readFileSync(join(migDir, f), 'utf8')).join('\n');

  const tables = [];
  const tableRe = /CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\(([\s\S]*?)\);/g;
  for (const m of sql.matchAll(tableRe)) {
    const name = m[1];
    const cols = m[2]
      .split('\n')
      .map((l) => l.trim().replace(/,$/, ''))
      .filter((l) => l && !l.startsWith('--'));
    tables.push({ name, cols });
  }

  const indexes = [];
  const idxRe = /CREATE\s+(UNIQUE\s+)?INDEX IF NOT EXISTS\s+(\w+)\s+ON\s+(\w+)\(([^)]+)\);/g;
  for (const m of sql.matchAll(idxRe)) {
    indexes.push({
      unique: Boolean(m[1]),
      name: m[2],
      table: m[3],
      cols: m[4].trim(),
    });
  }

  const lines = [
    '# D1 Database Schema',
    '',
    `<!-- Generated by scripts/generate-docs-ref.mjs from ${files.map((f) => `migrations/${f}`).join(', ')} -->`,
    '',
    `Defined in ${files.map((f) => `\`migrations/${f}\``).join(', ')}.`,
    '',
    '## Tables',
    '',
  ];

  for (const t of tables) {
    lines.push(`### \`${t.name}\``, '');
    lines.push('| Column | Definition |', '|---|---|');
    for (const col of t.cols) {
      const spaceIdx = col.search(/\s+/);
      if (spaceIdx === -1) {
        lines.push(`| \`${col}\` | — |`);
      } else {
        const colName = col.slice(0, spaceIdx);
        const def = col.slice(spaceIdx + 1).replace(/\|/g, '\\|');
        lines.push(`| \`${colName}\` | \`${def}\` |`);
      }
    }
    lines.push('');
  }

  lines.push('## Indexes', '', '| Index | Table | Columns | Unique |', '|---|---|---|---|');
  for (const idx of indexes) {
    lines.push(`| \`${idx.name}\` | \`${idx.table}\` | \`${idx.cols}\` | ${idx.unique ? 'Yes' : 'No'} |`);
  }
  lines.push('');

  writeFileSync(join(OUT_DIR, 'schema.md'), lines.join('\n'));
}

generateBindingsAndEnv();
generateRoutes();
generateSchema();
console.log('Generated docs/src/reference/{bindings-and-env,routes,schema}.md');
